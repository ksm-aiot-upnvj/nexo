"""Schema cleanup and validation for model supplied tool calls."""


def sanitize_parameters(schema: dict) -> dict:
    """
    Recursively sanitizes JSON schema parameters:
    - Strips '$defs' and all 'title' attributes generated by Pydantic.
    - Simplifies nullable 'anyOf': [{'type': 'T'}, {'type': 'null'}] -> {'type': 'T'}.
    - Trims parameter descriptions to single-line concise text.
    - Removes empty/redundant metadata.
    """
    if not isinstance(schema, dict):
        return schema

    cleaned = {}
    for key, value in schema.items():
        if key in ("title", "$defs"):
            continue

        if key in ("anyOf", "oneOf") and isinstance(value, list):
            non_null = [
                item
                for item in value
                if isinstance(item, dict) and item.get("type") != "null"
            ]
            if len(non_null) == 1:
                sub_cleaned = sanitize_parameters(non_null[0])
                cleaned.update(sub_cleaned)
                continue

        if key == "description" and isinstance(value, str):
            first_line = value.strip().split("\n")[0].split("Args:")[0].strip()
            cleaned[key] = first_line
            continue

        if key == "default" and value is None:
            continue

        if key == "additionalProperties" and value is True:
            continue

        if isinstance(value, dict):
            cleaned[key] = sanitize_parameters(value)
        elif isinstance(value, list):
            cleaned[key] = [
                sanitize_parameters(item) if isinstance(item, dict) else item
                for item in value
            ]
        else:
            cleaned[key] = value

    if cleaned.get("type") == "object" and "properties" not in cleaned:
        cleaned["properties"] = {}

    return cleaned


def sanitize_tool_schema(tool: dict) -> dict:
    """Sanitizes an OpenAI-compatible tool definition to reduce token overhead."""
    if not isinstance(tool, dict):
        return tool

    fn = tool.get("function", {})
    if not fn:
        return tool

    desc = fn.get("description", "")
    if isinstance(desc, str):
        desc = desc.strip().split("\n")[0].split("Args:")[0].strip()

    params = fn.get("parameters", {})
    sanitized_params = sanitize_parameters(params) if isinstance(params, dict) else {}

    return {
        "type": "function",
        "function": {
            "name": fn.get("name", "unknown"),
            "description": desc,
            "parameters": sanitized_params,
        },
    }


def sanitize_tools_list(tools: list) -> list:
    """Applies schema sanitization to a list of tool definitions."""
    if not tools:
        return []
    return [sanitize_tool_schema(t) for t in tools]


def _validate_schema_value(value, schema: dict, path: str = "arguments") -> str | None:
    """Validate the common JSON Schema constraints used by tool arguments."""
    expected_type = schema.get("type")
    type_checks = {
        "object": lambda item: isinstance(item, dict),
        "array": lambda item: isinstance(item, list),
        "string": lambda item: isinstance(item, str),
        "integer": lambda item: isinstance(item, int) and not isinstance(item, bool),
        "number": lambda item: (
            isinstance(item, (int, float)) and not isinstance(item, bool)
        ),
        "boolean": lambda item: isinstance(item, bool),
        "null": lambda item: item is None,
    }
    check = type_checks.get(expected_type)
    if check and not check(value):
        return f"{path} must be {expected_type}"
    if "enum" in schema and value not in schema["enum"]:
        return f"{path} must be one of the allowed values"
    if isinstance(value, dict):
        properties = schema.get("properties", {})
        missing = [key for key in schema.get("required", []) if key not in value]
        if missing:
            return f"{path} is missing required field(s): {', '.join(missing)}"
        if schema.get("additionalProperties") is False:
            unexpected = [key for key in value if key not in properties]
            if unexpected:
                return f"{path} contains unexpected field(s): {', '.join(unexpected)}"
        for key, item in value.items():
            child_schema = properties.get(key)
            if child_schema:
                error = _validate_schema_value(item, child_schema, f"{path}.{key}")
                if error:
                    return error
    if isinstance(value, list) and isinstance(schema.get("items"), dict):
        for index, item in enumerate(value):
            error = _validate_schema_value(item, schema["items"], f"{path}[{index}]")
            if error:
                return error
    return None


def _validate_tool_arguments(
    tool_name: str, arguments: dict, tool_schemas: dict[str, dict]
) -> str | None:
    """Reject unregistered tools and validate arguments against the declared schema."""
    schema = tool_schemas.get(tool_name)
    if schema is None:
        return f"Unknown tool name: {tool_name}"
    return _validate_schema_value(arguments, schema)
